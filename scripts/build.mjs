// Generates every port of the theme from palette/<name>.json.
// Usage: node scripts/build.mjs   (no dependencies)

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { derive } from "./derive.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = "Generated by scripts/build.mjs — do not edit, change palette/*.json instead";

const out = (path, content) => {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  console.log(`  ${path}`);
};

