// ---------------------------------------------------------------- main

const palettes = readdirSync(join(root, "palette")).filter((f) => f.endsWith(".json"));
for (const file of palettes) {
  const spec = JSON.parse(readFileSync(join(root, "palette", file), "utf8"));
  for (const [variant, raw] of Object.entries(spec.variants)) {
    const palette = {
      family: spec.name,
      variant,
      name: `${spec.name}-${variant}`,
      displayName: `${spec.displayName} ${variant[0].toUpperCase()}${variant.slice(1)}`,
      appearance: variant,
      ...derive(variant, raw),
    };
    console.log(`${palette.displayName}:`);
    for (const build of Object.values(targets)) out(...build(palette));
  }
}
